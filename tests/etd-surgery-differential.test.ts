/**
 * Differential test: the TypeScript ETD port vs the Python runner.
 *
 * `server/vrm/etd/surgery.ts` and `vehicle-class.ts` are ports of
 * `etd-runner/scripts/book_cutover.py` and `vehicle_class.py`. Both originals earned
 * their quirks from real failures — a reservation booked in the wrong person's name, a
 * reservation booked at the template's branch behind correct-looking display strings, a
 * reservation booked in the template's class while the note promised another. A port
 * that is 99% right reproduces exactly those bugs, so "looks equivalent" is not a
 * standard worth anything here.
 *
 * The expectations are GENERATED by running the Python (see
 * tests/fixtures/etd-surgery/generate.py) rather than written by hand, so nobody's
 * reading of the Python is in the loop. Regenerate after any change to either side:
 *
 *     etd-runner/.venv/bin/python tests/fixtures/etd-surgery/generate.py
 *
 * The fixtures hold only the paths the surgery CHANGES plus their new (synthetic)
 * values — never the captured template's contents, which are real PII.
 *
 * No network, no database, no external system.
 */
