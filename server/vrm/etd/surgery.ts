const REF_DIR = path.resolve(process.cwd(), "etd-runner", "reference");
export const TEMPLATE_PATH = path.join(REF_DIR, "savedr_request.json");
export const MAPPING_PATH = path.join(REF_DIR, "etd_user_mapping.json");

let templateCache: Record<string, unknown> | null = null;
let mappingCache: Record<string, string> | null = null;

/** The captured savedr model. Throws when absent — it cannot be reconstructed. */
export function loadSavedrTemplate(): Record<string, unknown> {
  if (!templateCache) {
    if (!fs.existsSync(TEMPLATE_PATH)) {
      throw new Error(
        `Missing ${TEMPLATE_PATH}. It is the captured reservation model and cannot be reconstructed; re-capture it.`,
      );
    }
    templateCache = JSON.parse(fs.readFileSync(TEMPLATE_PATH, "utf-8"));
  }
  return templateCache!;
}

/** LDAP → ETD username (SHS- collision handles). Throws when absent. */
export function loadUserMapping(): Record<string, string> {
  if (!mappingCache) {
    if (!fs.existsSync(MAPPING_PATH)) {
      throw new Error(`${MAPPING_PATH} is missing. Run reconcile_roster.py or every SHS- collision case will fail to resolve.`);
    }
    mappingCache = JSON.parse(fs.readFileSync(MAPPING_PATH, "utf-8"));
  }
  return mappingCache!;
}

/** The template's own journey/reference ids, needed by retarget(). */
export function templateOldIds(template: Record<string, unknown>): { oldJ: string | null; oldR: string | null } {
  const jvm = (template.journeyViewModel ?? {}) as Record<string, unknown>;
  const oldJ = (template.journeyUId as string) || (jvm.journeyProfilerUId as string) || null;
  const oldR = (jvm.referenceNumber as string) || null;
  return { oldJ, oldR };
}

/** Deep copy for per-booking surgery; the cached template must stay pristine. */
export function cloneTemplate(template: Record<string, unknown>): Record<string, unknown> {
  return structuredClone(template);
}
