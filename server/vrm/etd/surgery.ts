const escapeRe = (s: string) => s.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

export function setDriver(
  model: Record<string, unknown>,
  user: Record<string, unknown>,
  ldap: string,
  techName: string | null | undefined,
  truck: string,
): string[] {
  const changed: string[] = [];

  let first = String(user.firstName ?? "").trim();
  let last = String(user.lastName ?? "").trim();
  if (!(first && last)) {
    // Fall back to the survey name. "SCOTT,CORNELIUS" is surname-first;
    // "ALONSO CHAVIRA" is not.
    const nm = String(techName ?? "").trim();
    if (nm.includes(",")) {
      const i = nm.indexOf(",");
      last = nm.slice(0, i);
      first = nm.slice(i + 1);
    } else {
      const parts = nm.split(/\s+/).filter(Boolean);
      if (parts.length > 1) {
        first = parts[0];
        last = parts.slice(1).join(" ");
      } else {
        first = nm;
        last = "";
      }
    }
    first = first.trim();
    last = last.trim();
  }
  if (!(first && last)) throw new Error(`cannot resolve a driver name for ${ldap}`);

  const email = String((user.emailAddress ?? user.email ?? "") as string).trim();
  let phone = String((user.mobileNumber ?? (user as any).phone ?? (user as any).contactNumber ?? "") as string).replace(/\D/g, "");
  if (!phone && email.includes("@tmomail.net")) {
    // Provisioning made every address <10-digit-phone>@tmomail.net, so the
    // local part IS the phone when the profile carries none elsewhere.
    const local = email.split("@", 1)[0] ?? email.slice(0, email.indexOf("@"));
    if (/^\d{10}$/.test(local)) phone = local;
  }
  const bobo = String(user.userId ?? "");

  for (const blk of ["driverViewModel", "driverViewModelForBOBO"]) {
    const d = model[blk];
    if (!d || typeof d !== "object" || Array.isArray(d)) continue;
    const dd = d as Record<string, unknown>;
    dd.firstName = first;
    dd.lastName = last;
    changed.push(`${blk}.firstName`, `${blk}.lastName`);
    if (email) {
      dd.emailAddress = email;
      changed.push(`${blk}.emailAddress`);
    }
    if (bobo) {
      dd.boboId = bobo;
      changed.push(`${blk}.boboId`);
    }
    if (phone) {
      const cp = dd.contactPhoneNumber;
      if (cp && typeof cp === "object" && !Array.isArray(cp)) {
        (cp as Record<string, unknown>).number = phone;
        (cp as Record<string, unknown>).selectedInternationalDiallingCode = "1";
        changed.push(`${blk}.contactPhoneNumber.number`);
      }
      // The captured string says (+44) against a US number. Write the
      // country code we actually set rather than preserving that.
      dd.contactPhoneNumberString = `(+1)${phone}`;
      changed.push(`${blk}.contactPhoneNumberString`);
    }
  }

  if ("driverName" in model) {
    model.driverName = `${first} ${last}`.toUpperCase();
    changed.push("driverName");
  }
  if (email && "driverEmail" in model) {
    model.driverEmail = email;
    changed.push("driverEmail");
  }

  // The fields ETD actually stores and shows the branch. `bookingReferences`
  // is NOT this.
  const fields = ((model.additionalInformation as Record<string, unknown>)?.additionalInformationFields ?? []) as unknown[];
  for (const fld of Array.isArray(fields) ? fields : []) {
    if (!fld || typeof fld !== "object" || Array.isArray(fld)) continue;
    const f = fld as Record<string, unknown>;
    const name = String(f.fieldName ?? "").trim().toUpperCase();
    if (name.startsWith("TRUCK")) {
      f.fieldValue = String(truck);
      changed.push("additionalInformation.TruckNumber");
    } else if (name.startsWith("LDAP")) {
      f.fieldValue = ldap;
      changed.push("additionalInformation.LDAP");
    }
  }

  // Belt and braces: replace the captured driver's values ANYWHERE they
  // remain, by value. The targeted rewrites above cover the fields we know;
  // this sweep covers the ones we don't (the category that produced JAS57HG8OU).
  const sub = new Map<string, string>([
    ["MARK", first.toUpperCase()], ["Mark", first], ["mark", first.toLowerCase()],
    ["RAY", last.toUpperCase()], ["Ray", last], ["ray", last.toLowerCase()],
    ["MARK RAY", `${first} ${last}`.toUpperCase()],
    ["MRAY0", ldap],
    ["37046", String(truck)],
    // The captured driver's phone is scrubbed UNCONDITIONALLY. Leaving it
    // because we happen not to know the replacement still texts him about
    // someone else's rental.
    ["7577522030@tmomail.net", email || ""],
    ["7577522030", phone || ""],
    ["(+44)7577522030", phone ? `(+1)${phone}` : ""],
    ["(+1)7577522030", phone ? `(+1)${phone}` : ""],
  ]);

  const sweep = (node: unknown): void => {
    if (node && typeof node === "object" && !Array.isArray(node)) {
      const obj = node as Record<string, unknown>;
      for (const k of Object.keys(obj)) {
        const v = obj[k];
        if (typeof v === "string") {
          if (sub.has(v)) {
            obj[k] = sub.get(v)!;
            changed.push(`sweep:${k}`);
          } else if (v.includes("7577522030")) {
            obj[k] = v.split("7577522030").join(phone || "");
            changed.push(`sweep:${k}`);
          } else if (v.includes("MRAY0")) {
            obj[k] = v.split("MRAY0").join(ldap);
            changed.push(`sweep:${k}`);
          }
        } else {
          sweep(v);
        }
      }
    } else if (Array.isArray(node)) {
      // Strings sitting directly in a list (bookingReferences is one)
      // must be rewritten in place, not just recursed past.
      for (let i = 0; i < node.length; i++) {
        const v = node[i];
        if (typeof v === "string") {
          if (sub.has(v)) {
            node[i] = sub.get(v)!;
            changed.push("sweep:list");
          } else if (v.includes("MRAY0")) {
            node[i] = v.split("MRAY0").join(ldap).split("37046").join(String(truck));
            changed.push("sweep:list");
          } else if (v.includes("37046")) {
            node[i] = v.split("37046").join(String(truck));
            changed.push("sweep:list");
          }
        } else {
          sweep(v);
        }
      }
    }
  };
  sweep(model);

  // Fail loudly if the captured driver survived anywhere. Checked as whole
  // tokens, not substrings: a bare "MARK" also matches "MARKET ST", which is
  // a real Enterprise branch address and produced a false alarm on ACOVAS.
  const mine = `${first} ${last} ${ldap} ${truck} ${email}`.toUpperCase();
  const blob = JSON.stringify(model).toUpperCase();
  const ghosts = ["MARK RAY", "MRAY0", "7577522030"];
  if (String(truck) !== "37046") ghosts.push("37046"); // the captured driver's truck number
  for (const ghost of ghosts) {
    if (mine.includes(ghost)) continue;
    if (new RegExp(`(?<![A-Z0-9])${escapeRe(ghost)}(?![A-Z0-9])`).test(blob)) {
      throw new Error(
        `captured driver '${ghost}' still present after retargeting ${ldap}; ` +
          "refusing to book. The template has fields this function does not know about.",
      );
    }
  }

  // The driver blocks specifically must now name this technician.
  for (const blk of ["driverViewModel", "driverViewModelForBOBO"]) {
    const d = (model[blk] ?? {}) as Record<string, unknown>;
    if (
      String(d.firstName ?? "").toUpperCase() !== first.toUpperCase() ||
      String(d.lastName ?? "").toUpperCase() !== last.toUpperCase()
    ) {
      throw new Error(`${blk} did not take the new driver for ${ldap}`);
    }
  }
  return changed;
}

