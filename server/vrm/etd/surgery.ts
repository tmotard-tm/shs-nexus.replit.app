/**
 * The branch string format is theirs, taken verbatim from the capture:
 *   "Portsmouth Airline Blvd. (2102),2841 AIRLINE BLVD,PORTSMOUTH,23701-2704"
 *   = `${customerFacingBranchName} (${branchCode}),${fullAddress}`
 * The display fields are for humans; the `locations` block carries the
 * MACHINE identifiers (branchCode / stationId) that ETD actually books.
 */
export function relocate(
  model: Record<string, unknown>,
  branch: Record<string, unknown>,
  place: Record<string, unknown>,
): void {
  const name = String(branch.customerFacingBranchName ?? (branch as any).branchName ?? "");
  const code = String(branch.branchCode ?? "");
  const addr = String(branch.fullAddress ?? "");
  const branchStr = `${name} (${code}),${addr}`;
  const lat = String(branch.latitude ?? place.latitude ?? "");
  const lon = String(branch.longitude ?? place.longitude ?? "");
  const psid = String(branch.peoplesoftBranchId ?? "");
  const stid = String(branch.stationId ?? "");
  // The capture has no space after (+1); the branch record has one.
  const phone = String(branch.formattedPhoneNumber ?? "").replace(/\s+/g, "");

  for (const k of ["startLocationString", "endLocationString", "branchAddress", "startServicingBranch", "endServicingBranch"]) {
    if (k in model) model[k] = branchStr;
  }
  if ("branchTelephone" in model) model.branchTelephone = phone;
  if ("locationsURL" in model) model.locationsURL = `${lat}/${lon}/${lat}/${lon}`;

  for (const [k, v] of [
    ["startLatitude", lat], ["startLongitude", lon],
    ["endLatitude", lat], ["endLongitude", lon],
    ["startLocationPeopleSoftId", psid], ["startLocationStationId", stid],
    ["endLocationPeopleSoftId", psid], ["endLocationStationId", stid],
  ] as Array<[string, string]>) {
    if (k in model) model[k] = v;
  }

  const jvm = model.journeyViewModel;
  if (jvm && typeof jvm === "object" && !Array.isArray(jvm)) {
    const j = jvm as Record<string, unknown>;
    for (const key of ["startLocation", "endLocation"]) {
      const loc = j[key];
      if (loc && typeof loc === "object" && !Array.isArray(loc)) {
        const l = loc as Record<string, unknown>;
        l.location = (place.location as string) || addr;
        l.latitude = lat;
        l.longitude = lon;
        if ("peopleSoftId" in l) l.peopleSoftId = psid;
        if ("stationId" in l) l.stationId = stid;
      }
    }
    for (const [k, v] of [
      ["endPeopleSoftId", psid], ["endStationId", stid],
      ["endLatitude", lat], ["endLongitude", lon],
    ] as Array<[string, string]>) {
      if (k in j) j[k] = v;
    }
    // The waypoint list still pointed at the captured branch's address.
    for (const pt of (j.allPoints as unknown[]) ?? []) {
      if (pt && typeof pt === "object" && !Array.isArray(pt) && "destination" in (pt as Record<string, unknown>)) {
        (pt as Record<string, unknown>).destination = (place.location as string) || addr;
      }
    }
  }

  const nameUpper = name.toUpperCase();
  const desc = `${nameUpper}, ${addr}`.split(",,").join(",");
  const locs = model.locations;
  if (locs && typeof locs === "object" && !Array.isArray(locs)) {
    const ld = locs as Record<string, unknown>;
    for (const key of ["startLocation", "endLocation"]) {
      const loc = ld[key];
      if (!loc || typeof loc !== "object" || Array.isArray(loc)) continue;
      const l = loc as Record<string, unknown>;
      if ("branchDescription" in l) l.branchDescription = desc;
      if ("branchDescriptionWithBranchCode" in l) l.branchDescriptionWithBranchCode = branchStr;
      if ("branchCode" in l) l.branchCode = code;
      if ("stationId" in l) l.stationId = stid || l.stationId;
      if ("locationEditorName" in l) l.locationEditorName = nameUpper;
      for (const [k, v] of [
        ["latitude", lat], ["longitude", lon],
        ["peopleSoftId", psid], ["peoplesoftBranchId", psid],
      ] as Array<[string, string]>) {
        if (k in l) l[k] = v;
      }
    }
  }

  // Refuse to book if the captured branch survives anywhere. '2102' alone
  // is too short to grep safely, so check the two machine identifiers in
  // field positions plus the city name as a token.
  if (code !== "2102") {
    const blob = JSON.stringify(model).toUpperCase();
    for (const ghost of ['"E12102"', '"2102"', "PORTSMOUTH AIRLINE"]) {
      if (blob.includes(ghost)) {
        throw new Error(
          `captured branch marker ${ghost} still present after relocating to ` +
            `${code}; refusing to book. relocate() has a field it does not know about.`,
        );
      }
    }
  }
}

