/**
 * THE FIELD THAT ACTUALLY DECIDES: classInfo[*].brandInfo[*].isSelected.
 * The header fields (carClassCode etc.) are decorative; the buried flag is
 * the selection, stored as the strings 'True' / 'False'.
 */
/**
 * Swap the captured additional-info block for the account's current field list.
 *
 * The captured block is a snapshot of the account as it stood when the browser capture
 * was taken, and it goes stale silently: ETD answers a mismatch with one sentence,
 * `REQUIRED FIELD MISSING: ADDITIONALINFO`, naming no field. Values arrive empty from the
 * definition endpoint; `setDriver` fills them immediately after.
 */
export function useAccountAdditionalInfo(
  model: Record<string, unknown>,
  liveFields: unknown[],
): string[] {
  let block = model.additionalInformation as Record<string, unknown> | undefined;
  if (!block || typeof block !== "object" || Array.isArray(block)) {
    block = {};
    model.additionalInformation = block;
  }
  const fields: Record<string, unknown>[] = [];
  for (const src of Array.isArray(liveFields) ? liveFields : []) {
    if (!src || typeof src !== "object" || Array.isArray(src)) continue;
    const fld = JSON.parse(JSON.stringify(src)) as Record<string, unknown>;
    fld.fieldValue = fld.fieldValue ?? "";
    fld.fieldValueDateString = fld.fieldValueDateString ?? "";
    fields.push(fld);
  }
  block.additionalInformationFields = fields;
  return fields.map((f) => String(f.fieldName ?? "").trim());
}

/**
 * Drop any bookingReferences entry labelled Truck Number.
 *
 * Enterprise removed that field from the account, so the label refers to nothing. The
 * truck number belongs in the reservation's special notes and is put there by
 * renderRequestSpecialNotes / renderSpecialNotes. Deliberately narrow: the cutover's
 * `CLOSE Enterprise Ticket` and `Holman ARI Claim` entries are not account fields
 * either, and they are what ties a converted reservation back to its Holman ticket.
 */
export function stripTruckNumberReference(model: Record<string, unknown>): number {
  const refs = model.bookingReferences;
  if (!Array.isArray(refs)) return 0;
  const kept = refs.filter(
    (r) => !(typeof r === "string" && /^\s*(SHS\s+)?truck\s*number\b/i.test(r)),
  );
  const dropped = refs.length - kept.length;
  if (dropped) model.bookingReferences = kept;
  return dropped;
}

/**
 * Refuse to commit while a mandatory additional-info field is still empty.
 *
 * Fails closed and BY NAME. If Enterprise adds a field nothing here knows how to fill,
 * the alternative is ETD's generic refusal, which cost hours to attribute on 2026-08-17.
 */
export function assertAdditionalInfoComplete(model: Record<string, unknown>, ldap: string): void {
  const block = model.additionalInformation as Record<string, unknown> | undefined;
  const fields = (block?.additionalInformationFields ?? []) as unknown[];
  const missing: string[] = [];
  for (const fld of Array.isArray(fields) ? fields : []) {
    if (!fld || typeof fld !== "object" || Array.isArray(fld)) continue;
    const f = fld as Record<string, unknown>;
    if (f.mandatory && !String(f.fieldValue ?? "").trim()) {
      missing.push(String(f.fieldName ?? "?").trim());
    }
  }
  if (missing.length) {
    throw new Error(
      `account requires additional-info field(s) nothing fills: ${missing.join(", ")} ` +
        `(ldap ${ldap}). Teach setDriver the field, or have Enterprise confirm the ` +
        "account configuration.",
    );
  }
}

export function setClass(model: Record<string, unknown>, pick: Record<string, unknown>): void {
  const code = String(pick.code ?? "").toUpperCase();
  const desc = String(pick.description ?? "");
  if (!code) throw new Error("set_class called with no class code");
  const pax = String(pick.passengers ?? "5");
  const bags = String(pick.bags ?? "3");

  const cc = model.carClass;
  if (cc && typeof cc === "object" && !Array.isArray(cc)) {
    const ccd = cc as Record<string, unknown>;
    const oldId = String(ccd.carClassId ?? "");
    // Keep the captured id's tail fields (door counts etc.) and swap the
    // parts we actually know. Format observed:
    // CODE|DESC|True|False|passengers|bags||3|4|Unspecified
    const parts = oldId.split("|");
    if (parts.length >= 6) {
      parts[0] = code;
      parts[1] = desc;
      parts[4] = pax;
      parts[5] = bags;
      ccd.carClassId = parts.join("|");
    } else {
      ccd.carClassId = `${code}|${desc}|True|False|${pax}|${bags}||3|4|Unspecified`;
    }
    ccd.carClassCode = code;
    ccd.carClass = desc;
  }
  if ("vehicleClass" in model) {
    model.vehicleClass = `${code} - ${desc}`;
  }

  let flippedOn = 0;
  const info =
    cc && typeof cc === "object" && !Array.isArray(cc)
      ? ((cc as Record<string, unknown>).carsInformation as Record<string, unknown> | undefined)
      : undefined;
  const entries = ((info ?? {}).classInfo ?? []) as unknown[];
  for (const e of Array.isArray(entries) ? entries : []) {
    if (!e || typeof e !== "object" || Array.isArray(e)) continue;
    const ed = e as Record<string, unknown>;
    const isTarget = String(ed.modelCode ?? "").toUpperCase() === code;
    for (const b of (ed.brandInfo as unknown[]) ?? []) {
      if (b && typeof b === "object" && !Array.isArray(b) && "isSelected" in (b as Record<string, unknown>)) {
        (b as Record<string, unknown>).isSelected = isTarget ? "True" : "False";
        if (isTarget) flippedOn += 1;
      }
    }
  }
  if (flippedOn === 0) {
    throw new Error(
      `class ${code} is not in the template's classInfo list; the selection ` +
        "flag cannot be set, so ETD would book the captured class. Refusing.",
    );
  }

  // Verify both layers took.
  const got = String(((model.carClass ?? {}) as Record<string, unknown>).carClassCode ?? "").toUpperCase();
  if (got !== code) {
    throw new Error(`carClassCode is '${got}' after set_class(${code}); refusing to book`);
  }
  const liveSel: string[] = [];
  for (const e of Array.isArray(entries) ? entries : []) {
    if (!e || typeof e !== "object" || Array.isArray(e)) continue;
    const ed = e as Record<string, unknown>;
    for (const b of (ed.brandInfo as unknown[]) ?? []) {
      if (b && typeof b === "object" && !Array.isArray(b) && String((b as Record<string, unknown>).isSelected) === "True") {
        liveSel.push(String(ed.modelCode).toUpperCase());
      }
    }
  }
  if (!(liveSel.length === 1 && liveSel[0] === code)) {
    throw new Error(`isSelected flags wrong after set_class(${code}): ${JSON.stringify(liveSel)}`);
  }
}

